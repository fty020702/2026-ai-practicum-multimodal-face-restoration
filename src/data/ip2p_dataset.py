from __future__ import annotations

"""Load the OFFICIAL InstructPix2Pix triplet format into this project's batch.

Dataset (one ~500 MB parquet shard, downloaded by scripts/fetch_ip2p_shard.py):
    timbrooks/instructpix2pix-clip-filtered
    columns: original_prompt, original_image, edit_prompt,
             edited_prompt, edited_image

Format mapping -- this is the whole point of "格式符合要求":

    official triplet                 project batch contract
    -----------------------------    --------------------------
    original_image (input)        -> degraded  [3,H,W] float [0,1]
    edited_image   (target)       -> clean     [3,H,W] float [0,1]
    edit_prompt    (instruction)  -> prompt    str
    original_prompt (caption)     -> task      str (metadata only)

No synthetic degradation is applied: the input/target pair comes straight from
the official release. [FACT] Those images were GENERATED by Stable Diffusion +
Prompt-to-Prompt (Brooks et al. CVPR 2023), they are NOT real photographs.
This loader makes that explicit rather than quietly relabelling them.

`ip2p_max_rows` limits how much of the shard is actually used for training,
per the user's 2026-11-13 instruction "不一定全部训练" (we do not have to
train on all of it). The full shard stays on disk as the ~500 MB dataset.

    D:/Anaconda/envs/ChatAI/python.exe src/train.py \
        --override configs/ip2p_500m.yaml --device cuda --steps 1000
"""

import hashlib
import io
import json
from collections import defaultdict
from pathlib import Path

import numpy as np
import torch
from torch.utils.data import Dataset

try:
    import pyarrow.parquet as pq
    from PIL import Image
    _HAS_DEPS = True
except ImportError:  # pragma: no cover
    _HAS_DEPS = False


def _decode(item, size: int) -> np.ndarray:
    """parquet image cell -> uint8 HWC ndarray, word-wise safe."""
    b = item.get("bytes") if isinstance(item, dict) else item
    if not b:
        raise ValueError("empty image cell in parquet")
    im = Image.open(io.BytesIO(b)).convert("RGB")
    if im.width != size or im.height != size:
        im = im.resize((size, size), Image.BILINEAR)
    # np.asarray(..., copy=True) requires NumPy >= 2.0; the ChatAI env has an
    # older numpy. np.array(..., copy=True) is the compatible equivalent and
    # is what the rest of this project already uses.
    return np.array(im, dtype=np.uint8, copy=True)


class IP2PShardDataset(Dataset):
    """One official parquet shard -> (degraded, clean, prompt) samples."""

    def __init__(self, cfg, num_pairs: int | None = None,
                 split: str = "train", root=None):
        if not _HAS_DEPS:
            raise RuntimeError("pyarrow + Pillow are required for IP2PShardDataset")
        d = cfg["data"]
        self.size = int(d["image_size"])
        self.root = Path(root) if root else Path(cfg["_root"])
        self.split = split
        self.max_rows = int(num_pairs or d.get("ip2p_max_rows", 800))
        self.collapse = bool(d.get("collapse_targets", False))
        # Control: replace the target with the INPUT image so the text has no
        # target to select. Used to reproduce the single-target confound A/B.
        self.collapse_to_input = bool(d.get("ip2p_collapse_to_input", False))

        rel = d.get("ip2p_parquet",
                    "data/ip2p_500m/raw/train-00000-of-00262-"
                    "57cebf95b4a9170c.parquet")
        self.parquet_path = self.root / rel
        if not self.parquet_path.is_file():
            raise FileNotFoundError(
                f"[ip2p] parquet shard not found: {self.parquet_path}\n"
                "  Run: scripts/fetch_ip2p_shard.py --shard 0\n"
                "  No silent fallback to synthetic data."
            )

        pf = pq.ParquetFile(self.parquet_path)
        names = pf.schema_arrow.names
        need = ("original_image", "edited_image", "edit_prompt")
        missing = [c for c in need if c not in names]
        if missing:
            raise RuntimeError(f"[ip2p] shard missing columns {missing}; "
                               f"actual schema={names}")
        cap_col = "original_prompt" if "original_prompt" in names else None
        cols = list(need) + ([cap_col] if cap_col else [])

        self.samples = []
        self.prompt_set = set()
        self.decode_errors: list[str] = []
        for batch in pf.iter_batches(batch_size=32, columns=cols):
            d0 = batch.column("original_image").to_pylist()
            d1 = batch.column("edited_image").to_pylist()
            ep = batch.column("edit_prompt").to_pylist()
            cp = batch.column(cap_col).to_pylist() if cap_col else [""] * len(d0)
            for x, y, e, c in zip(d0, d1, ep, cp):
                if len(self.samples) >= self.max_rows:
                    break
                try:
                    xim = _decode(x, self.size)
                    yim = _decode(y, self.size) if not self.collapse_to_input else xim
                except Exception as ex:                  # noqa: BLE001
                    if len(self.decode_errors) < 5:
                        self.decode_errors.append(
                            f"{type(ex).__name__}: {str(ex)[:160]}")
                    continue
                prompt = (e or "").strip() or "make the requested edit"
                self.prompt_set.add(prompt)
                self.samples.append({
                    "x": xim, "y": yim, "prompt": prompt,
                    "task": (c or "").strip()[:120],
                    "hash": hashlib.sha1(
                        x.get("bytes") if isinstance(x, dict) else x
                    ).hexdigest()[:16],
                })
            if len(self.samples) >= self.max_rows:
                break

        if not self.samples:
            raise RuntimeError(
                f"[ip2p] no decodable rows in shard; first errors="
                f"{self.decode_errors}; cols={cols}; max_rows={self.max_rows}")
        self.source = "ip2p_official_triplet"
        self.k = 1
        self.n_shard_rows = pf.metadata.num_rows

    # ------------------------------------------------------------------ #
    def __len__(self) -> int:
        return len(self.samples)

    @staticmethod
    def _t(a: np.ndarray) -> torch.Tensor:
        return torch.from_numpy(a.copy()).permute(2, 0, 1).float() / 255.0

    def __getitem__(self, idx: int) -> dict:
        s = self.samples[idx]
        return {
            "clean": self._t(s["y"]),
            "degraded": self._t(s["x"]),
            "task": s["task"],
            "prompt": s["prompt"],
            "target_id": "edited_image",
            "group_id": idx,
            "ip2p_hash": s["hash"],
        }

    def all_prompts(self) -> list[str]:
        """Exact finite prompt set, for offline Qwen3 pre-encoding."""
        return sorted(self.prompt_set)

    def write_manifest(self) -> None:
        """Persist a human-readable manifest of the subset actually used."""
        out = self.parquet_path.parent.parent / "train_subset.jsonl"
        out.write_text("".join(
            json.dumps({
                "row": i, "ip2p_input_hash": s["hash"],
                "edit_prompt": s["prompt"],
                "original_prompt": s["task"],
                "image_size": self.size,
            }, ensure_ascii=False) + "\n"
            for i, s in enumerate(self.samples)
        ), encoding="utf-8")
